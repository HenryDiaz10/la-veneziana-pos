import { Router } from 'express';
import { autenticar } from '../middlewares/autenticar.js';
import { exigirPermiso } from '../middlewares/exigirPermiso.js';
import { abrir, cajaActual, recuperar, resolver } from '../controllers/pedidos.controller.js';
import * as cierre from '../controllers/caja-cierre.controller.js';
const router = Router();
router.use(autenticar, exigirPermiso('caja', 'gestionar'));
router.get('/sesion', cajaActual);
router.get('/operaciones/:tipo/:clave', cierre.recuperar);
router.post('/operaciones/:tipo/:clave/resolver', cierre.resolver);
router.get('/sesiones/:id/resumen', cierre.resumen);
router.post('/sesiones/:id/movimientos', cierre.movimiento);
router.post('/sesiones/:id/cierre', cierre.cerrar);
router.get('/operaciones/:clave', recuperar);
router.post('/operaciones/:clave/resolver', resolver);
router.post('/sesiones', abrir);
export default router;
